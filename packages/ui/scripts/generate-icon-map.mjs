import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";
import { join, relative, sep } from "path";
import { fileURLToPath } from "url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const ROOT = join(__dirname, "..");

const CONST_FILE = join(ROOT, "src/const/index.ts");
const GENERATED_DIR = join(ROOT, "src/generated");
const GENERATED_FILE = join(GENERATED_DIR, "icon-map.ts");

const SCAN_DIRS = [
  join(ROOT, "src"),
  join(ROOT, "../../apps/web-main"),
  join(ROOT, "../../apps/web-prosper"),
];

const EXCLUDE_DIRS = new Set(["generated", "node_modules", "__stories__", "dist", ".next"]);
const EXCLUDE_FILES = new Set([
  "Icon.tsx",
  join(ROOT, "src/const/index.ts"),
]);

function toPascalCase(id) {
  return id
    .replace(/^phosphor\./, "")
    .split("_")
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join("");
}

function extractAllIcons() {
  const content = readFileSync(CONST_FILE, "utf-8");
  const ids = new Set();
  const regex = /["'](phosphor\.[a-z_]+)["']/g;
  let match;
  while ((match = regex.exec(content)) !== null) {
    ids.add(match[1]);
  }
  const all = [...ids].sort();
  return all.map((id) => [id, toPascalCase(id)]);
}

function findUsedIcons(allIconIds) {
  const used = new Set();
  const idSet = new Set(allIconIds.map(([id]) => id));

  function walk(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (EXCLUDE_DIRS.has(entry.name)) continue;
        if (entry.name.startsWith(".")) continue;
        walk(join(dir, entry.name));
      } else if (entry.name.endsWith(".ts") || entry.name.endsWith(".tsx")) {
        const fp = join(dir, entry.name);
        if (EXCLUDE_FILES.has(entry.name) || EXCLUDE_FILES.has(fp)) continue;
        const content = readFileSync(fp, "utf-8");
        const matches = content.matchAll(/(?:icon|id)(?:\s*[:=])\s*["'](phosphor\.[a-z_]+)["']/g);
        for (const m of matches) {
          if (idSet.has(m[1])) used.add(m[1]);
        }
      }
    }
  }

  for (const dir of SCAN_DIRS) {
    if (existsSync(dir)) walk(dir);
  }

  return used;
}

function generate(allIcons, usedIds) {
  const direct = allIcons.filter(([id]) => usedIds.has(id));
  const lazy = allIcons.filter(([id]) => !usedIds.has(id));

  const lines = [
    '// Auto-generated by scripts/generate-icon-map.mjs — do not edit manually',
    '// Direct imports for icons used in source code',
    '// Lazy dynamic imports for all other icons (loaded on first render)',
    '',
    "import dynamic from 'next/dynamic'",
    "import type { ForwardRefExoticComponent, RefAttributes, SVGAttributes } from 'react'",
    '',
  ];

  if (direct.length > 0) {
    const names = direct.map(([, name]) => name).join(", ");
    lines.push(`import { ${names} } from '@phosphor-icons/react'`);
    lines.push('');
  }

  lines.push("type IconComponent = ForwardRefExoticComponent<SVGAttributes<SVGSVGElement> & RefAttributes<SVGSVGElement>>");
  lines.push('');
  lines.push("export const iconMap: Record<string, IconComponent> = {");

  for (const [id, name] of direct) {
    lines.push(`  "${id}": ${name},`);
  }

  if (direct.length > 0 && lazy.length > 0) lines.push('');

  for (const [id, name] of lazy) {
    lines.push(`  "${id}": dynamic(() => import('@phosphor-icons/react/dist/icons/${name}').then(m => ({ default: m.${name} }))) as IconComponent,`);
  }

  lines.push('};');
  lines.push('');

  return lines.join('\n');
}

const allIcons = extractAllIcons();
const usedIds = findUsedIcons(allIcons);
const output = generate(allIcons, usedIds);

if (!existsSync(GENERATED_DIR)) {
  // mkdir -p equivalent
  const parts = GENERATED_DIR.split(sep);
  for (let i = 0; i < parts.length; i++) {
    const p = parts.slice(0, i + 1).join(sep);
    if (!existsSync(p)) {
      // simple mkdir
      const { execSync } = await import('child_process');
      execSync(`mkdir -p "${GENERATED_DIR}"`);
      break;
    }
  }
}

writeFileSync(GENERATED_FILE, output, "utf-8");

const usedCount = usedIds.size;
const totalCount = allIcons.length;
const lazyCount = totalCount - usedCount;
console.log(`✓ Generated icon map: ${usedCount} direct + ${lazyCount} lazy = ${totalCount} total`);
